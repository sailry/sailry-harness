use super::*;
use serde_json::json;

const PACKAGE: &str = "script-errors";
const SOURCE: &str = r#"
import {prepareTransaction,completeRequest} from 'sailry/sdk';
export function fail() { throw new Error('No active goal exists'); }
export async function reject() { throw new Error('Goal changed; read it before updating'); }
export function accessor() {
  const error = new Error();
  Object.defineProperty(error,'message',{get() { while (true) {} }});
  throw error;
}
export async function mixed() {
  await completeRequest(prepareTransaction([
    {kind:'conversation_write',data:{key:'partial',value:1,expected_revision:'0'}},
    {kind:'write',data:{key:'foreign',value:1,expected_revision:'0'}},
    {kind:'notify',data:{title:'Notice',message:'Do not publish',kind:'info',session:null}}
  ]));
}
"#;

async fn install(fixture: &process::Fixture) -> plugin::Context {
    let root = fixture.root.join("package");
    std::fs::create_dir_all(root.join("dev.sailry.platform/host")).unwrap();
    std::fs::write(root.join("dev.sailry.platform/host/main.js"), SOURCE).unwrap();
    let handlers = ["fail", "reject", "accessor", "mixed"];
    let tools: Vec<_> = handlers.iter().map(|name| json!({
        "name":name,"description":"Inspect bounded script failures", "handler":{
            "name":name,"parameters":{"type":"object","properties":{},"additionalProperties":false,"required":[]}
        }
    })).collect();
    std::fs::write(root.join("plugin.json"),json!({
        "$schema":"https://agent-plugins.org/schemas/1.0.0/plugin.schema.json",
        "name":PACKAGE,"version":"0.1.0","extensions":{"dev.sailry.platform":{
            "api_version":"v1","actions":["storage.read","storage.write","conversation.read","conversation.control"],
            "host":{"entry":"dev.sailry.platform/host/main.js","resources":["dev.sailry.platform/host/main.js"],"handlers":handlers},
            "tools":tools
        }}
    }).to_string()).unwrap();
    let Output::Plugin(package) = fixture
        .client
        .execute(fixture.client.prepare(Command::InstallPlugin {
            worktree: fixture.session.worktree,
            path: "package".into(),
            name: PACKAGE.into(),
            expected_revision: 0,
            expected_digest: None,
        }))
        .await
        .unwrap()
    else {
        panic!("package expected")
    };
    assert!(package.issues.is_empty(), "{:?}", package.issues);
    plugin::Context {
        invocation: None,
        turn: None,
        surface: Default::default(),
        package: package.summary.reference(),
        worktree: Some(fixture.session.worktree),
        session: Some(fixture.session.id),
    }
}

#[tokio::test]
async fn reports_errors_and_rejects_partial_transactions() {
    for remote in [false, true] {
        let names = ["fail", "reject", "accessor", "mixed"];
        let server = Server::tools(
            names
                .iter()
                .map(|name| (plugin_tool(PACKAGE, name), json!({})))
                .collect(),
        )
        .await;
        let fixture = process::Fixture::packages(remote, &server, &[]).await;
        let scope = install(&fixture).await;
        for (handler, message) in [
            ("fail", "No active goal exists"),
            ("reject", "Goal changed; read it before updating"),
            ("accessor", "Exception generated by QuickJS"),
        ] {
            let fault = fixture
                .client
                .execute(
                    fixture
                        .client
                        .prepare(Command::CallPlugin {
                            handler: handler.into(),
                            input: json!({}),
                        })
                        .with_plugin(scope.clone()),
                )
                .await
                .unwrap_err();
            assert_eq!(fault.code, ErrorCode::InvalidRequest);
            assert_eq!(
                fault.message,
                format!("plugin JavaScript execution failed: {message}")
            );
        }
        let Output::QueuedTurn(turn) = fixture
            .client
            .execute(fixture.client.prepare(Command::SubmitTurn {
                session: fixture.session.id,
                expected_revision: fixture.session.revision,
                message: "Inspect script failures without changing records".into(),
            }))
            .await
            .unwrap()
        else {
            panic!("turn expected")
        };
        let page = finished(&fixture.client, fixture.session.id, turn.id).await;
        let outputs: Vec<_> = page
            .entries
            .iter()
            .flat_map(|entry| &entry.parts)
            .filter_map(|part| {
                if let Part::ToolResult { result, .. } = part {
                    Some(result)
                } else {
                    None
                }
            })
            .collect();
        assert_eq!(outputs.len(), 4);
        for (index, message) in [
            "No active goal exists",
            "Goal changed; read it before updating",
            "Exception generated by QuickJS",
            "script tools cannot dispatch durable commands",
        ]
        .iter()
        .enumerate()
        {
            assert!(
                outputs[index]["error"].as_str().unwrap().contains(message),
                "{}",
                outputs[index]
            );
        }
        let Output::PluginConversationValue(value) = fixture
            .client
            .execute(
                fixture
                    .client
                    .prepare(Command::ReadPluginConversationValue {
                        key: "partial".into(),
                    })
                    .with_plugin(scope.clone()),
            )
            .await
            .unwrap()
        else {
            panic!("conversation value expected")
        };
        assert!(!value.present);
        assert_eq!(value.revision, 0);
        let Output::PluginValue(value) = fixture
            .client
            .execute(
                fixture
                    .client
                    .prepare(Command::ReadPluginValue {
                        key: "foreign".into(),
                    })
                    .with_plugin(scope),
            )
            .await
            .unwrap()
        else {
            panic!("value expected")
        };
        assert!(!value.present);
        assert_eq!(value.revision, 0);
        let profile = fixture.node.profile().to_owned();
        fixture.node.shutdown().await.unwrap();
        let node = Node::start_empty(profile).await.unwrap();
        let client = Client::new(if remote {
            fixture.controller.handle().remote(node.link().address())
        } else {
            node.local()
        });
        assert_eq!(history(&client, fixture.session.id).await, page);
        node.shutdown().await.unwrap();
        fixture.controller.close().await.unwrap();
    }
}
