use super::*;

#[test]
fn reports_plain_errors_and_rejections() {
    for source in [
        "export function run() { throw new Error('No active goal exists'); }",
        "export async function run() { throw new Error('No active goal exists'); }",
        "throw new Error('No active goal exists'); export function run() {}",
    ] {
        let fault = execute(source, CancellationToken::new(), Duration::from_secs(2)).unwrap_err();
        assert_eq!(fault.code, ErrorCode::InvalidRequest);
        assert_eq!(
            fault.message,
            "plugin JavaScript execution failed: No active goal exists"
        );
    }
    let fault = execute(
        "export function run() { const error = new Error('Goal changed'); error.code = 'revision_conflict'; throw error; }",
        CancellationToken::new(), Duration::from_secs(2),
    ).unwrap_err();
    assert_eq!(fault.code, ErrorCode::RevisionConflict);
    assert_eq!(
        fault.message,
        "plugin JavaScript execution failed: Goal changed"
    );
}

#[test]
fn never_evaluates_thrown_objects_or_accessors() {
    for source in [
        "export function run() { throw 'No active goal exists'; }",
        "export function run() { throw {get message() { while (true) {} }, toString() { while (true) {} }}; }",
        "export function run() { const error = new Error(); Object.defineProperty(error, 'message', {get() { while (true) {} }}); throw error; }",
        "export function run() { const error = new Error(); delete error.message; Object.defineProperty(Error.prototype, 'message', {get() { while (true) {} }}); throw error; }",
        "export function run() { throw new Proxy(new Error('hidden'), {getOwnPropertyDescriptor() { while (true) {} }}); }",
        "export function run() { throw new Error('x'.repeat(1025)); }",
        "export function run() { throw new Error('🙂'.repeat(300)); }",
        "export function run() { const error = new Error(); error.message = {toString() { while (true) {} }}; throw error; }",
    ] {
        let fault = execute(source, CancellationToken::new(), Duration::from_secs(2)).unwrap_err();
        assert_eq!(fault.code, ErrorCode::InvalidRequest);
        assert_eq!(
            fault.message,
            "plugin JavaScript execution failed: Exception generated by QuickJS"
        );
    }
}

#[test]
fn retains_pristine_intrinsics_and_bounded_codes() {
    for setup in [
        "Object.getOwnPropertyDescriptor = () => { while (true) {} }; Object.hasOwn = () => { while (true) {} };",
        "Object.defineProperty(Object.prototype, 'value', {get() { while (true) {} }});",
    ] {
        let source = format!(
            "export function run() {{ const error = new Error('Goal changed'); Object.defineProperty(error, 'code', {{get() {{ while (true) {{}} }} }}); {setup} throw error; }}"
        );
        let fault = execute(&source, CancellationToken::new(), Duration::from_secs(2)).unwrap_err();
        assert_eq!(fault.code, ErrorCode::InvalidRequest);
        assert_eq!(
            fault.message,
            "plugin JavaScript execution failed: Goal changed"
        );
    }
    for code in ["unknown".to_owned(), "x".repeat(33)] {
        let source = format!(
            "export function run() {{ const error = new Error('Goal changed'); error.code = {code:?}; throw error; }}"
        );
        let fault = execute(&source, CancellationToken::new(), Duration::from_secs(2)).unwrap_err();
        assert_eq!(fault.code, ErrorCode::InvalidRequest);
    }
}
