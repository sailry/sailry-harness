const (
	inputBytes    = 10 * 1024 * 1024
	artifactBytes = 20 * 1024 * 1024
)

func invalid(message string) error { return fault(protocol.ErrorCodeInvalidRequest, message) }

// readInput reads one regular file below root through the confined file
// service, refusing anything larger than the transfer limit.
func readInput(ctx context.Context, root, relative string) ([]byte, error) {
	confined, err := core.OpenFiles(root, core.RestrictedFiles)
	if err != nil {
		return nil, err
	}
	defer confined.Close()
	file, err := confined.Open(relative)
	if err != nil {
		return nil, err
	}
	defer file.Close()
	stop := context.AfterFunc(ctx, func() { _ = file.Close() })
	defer stop()
	data, err := io.ReadAll(io.LimitReader(file, inputBytes+1))
	if err != nil {
		if ctx.Err() != nil {
			return nil, ctx.Err()
		}
		return nil, invalid("browser file could not be read")
	}
	if len(data) > inputBytes {
		return nil, invalid("browser file exceeds 10 MiB")
	}
	return data, nil
}

// stageUpload copies a worktree file into the session's temporary directory.
// The browser only ever receives the staged copy. Setting a file input only
// records the path: the page reads the bytes when a form is submitted or a
// script sends them, in a later call. The copy therefore stays until the
// browser closes; only the oldest go once stagedUploads are kept.
func (session *session) stageUpload(ctx context.Context, root string, arguments map[string]any) (string, error) {
	relative, ok := arguments["file_path"].(string)
	if !ok {
		return "", invalid("file_path is required")
	}
	data, err := readInput(ctx, root, relative)
	if err != nil {
		return "", err
	}
	staging, err := os.MkdirTemp(session.temporary, "upload-")
	if err != nil {
		return "", invalid("browser upload staging failed")
	}
	staged := filepath.Join(staging, path.Base(filepath.ToSlash(relative)))
	if err := os.WriteFile(staged, data, 0o600); err != nil {
		_ = os.RemoveAll(staging)
		return "", invalid("browser upload staging failed")
	}
	session.uploads = append(session.uploads, staging)
	for len(session.uploads) > stagedUploads {
		_ = os.RemoveAll(session.uploads[0])
		session.uploads = session.uploads[1:]
	}
	return staged, nil
}

// save publishes generated bytes below assets/generated in the worktree.
func (browsers *Browsers) save(ctx context.Context, root, name string, data []byte) (string, error) {
	confined, err := core.OpenFiles(root, core.RestrictedFiles)
	if err != nil {
		return "", err
	}
	defer confined.Close()
	target := "assets/generated/" + name
	for _, directory := range []string{"assets", "assets/generated"} {
		if err := confined.CreateDirectory(directory); err != nil {
			return "", err
		}
	}
	file, err := confined.PrepareFileTarget(ctx, target, nil, artifactBytes)
	if err != nil {
		return "", err
	}
	if ctx.Err() != nil {
		_ = file.Close()
		return "", fault(protocol.ErrorCodeCancelled, "media save cancelled")
	}
	sum := blake3.Sum256(data)
	if _, err := file.Write(bytes.NewReader(data), uint64(len(data)), hex.EncodeToString(sum[:])); err != nil {
		return "", err
	}
	if browsers.options.Changed != nil {
		browsers.options.Changed(root)
	}
	return target, nil
}

// artifact moves a capture out of the result. A PDF is always saved in the
// worktree; a screenshot returns as bounded inline media and is saved on
// request.
func (browsers *Browsers) artifact(ctx context.Context, call Call, result map[string]any, save bool) (map[string]any, error) {
	field, pdf := "", false
	switch call.Action {
	case protocol.ExternalBrowserActionScreenshot:
		field = "base64_image"
	case protocol.ExternalBrowserActionPrintToPdf:
		field, pdf = "pdf_base64", true
	default:
		return nil, nil
	}
	encoded, ok := result[field].(string)
	delete(result, field)
	if !ok {
		return nil, invalid("browser artifact is missing its data")
	}
	data, err := base64.StdEncoding.DecodeString(encoded)
	if err != nil {
		return nil, invalid("invalid browser artifact encoding")
	}
	if len(data) > artifactBytes {
		return nil, invalid("browser artifact exceeds 20 MiB")
	}
	if pdf {
		saved, err := browsers.save(ctx, call.Root, "browser-"+call.Request.String()+".pdf", data)
		if err != nil {
			return nil, err
		}
		result["path"] = saved
		return nil, nil
	}
	// A capture is as large as its subject: an element capture covers the
	// whole element. It is reduced to the size every tool image has.
	source, sent, image, err := files.PrepareCapture(data)
	if err != nil {
		return nil, err
	}
	facts := source
	if sent != nil {
		facts = *sent
	}
	result["mime_type"], result["width"], result["height"], result["saved_to_artifacts"] = facts.MimeType, facts.Width, facts.Height, save
	if save {
		extension := strings.TrimPrefix(facts.MimeType, "image/")
		if extension == "jpeg" {
			extension = "jpg"
		}
		saved, err := browsers.save(ctx, call.Root, "browser-"+call.Request.String()+"."+extension, image)
		if err != nil {
			return nil, err
		}
		result["path"] = saved
	}
	return map[string]any{"mime_type": facts.MimeType, "data": base64.StdEncoding.EncodeToString(image)}, nil
}

// downloads lists the completed downloads of the session's browser.
func (session *session) downloads(node protocol.NodeID) (map[string]any, error) {
	entries, err := os.ReadDir(filepath.Join(session.temporary, "downloads"))
	if err != nil {
		return nil, invalid("browser download listing failed")
	}
	listed := []any{}
	truncated := false
	size := 0
	for _, entry := range entries {
		info, err := entry.Info()
		if err != nil || !info.Mode().IsRegular() || strings.HasSuffix(entry.Name(), ".crdownload") {
			continue
		}
		item := map[string]any{"name": entry.Name(), "size": info.Size()}
		encoded, _ := json.Marshal(item)
		if size += len(encoded) + 1; size > resultBytes-256 {
			truncated = true
			break
		}
		listed = append(listed, item)
	}
	return map[string]any{"execution_node": node, "files": listed, "truncated": truncated}, nil
}

// saveDownload copies one completed download into the worktree.
func (browsers *Browsers) saveDownload(ctx context.Context, session *session, call Call, arguments map[string]any) (map[string]any, error) {
	name, ok := arguments["name"].(string)
	if !ok {
		return nil, invalid("download name is required")
	}
	if name == "" || name == "." || name == ".." || strings.ContainsAny(name, `/\`) || strings.HasSuffix(name, ".crdownload") {
		return nil, invalid("select a completed download file name")
	}
	data, err := readInput(ctx, filepath.Join(session.temporary, "downloads"), name)
	if err != nil {
		return nil, err
	}
	saved, err := browsers.save(ctx, call.Root, "browser-"+call.Request.String()+"-"+name, data)
	if err != nil {
		return nil, err
	}
	return map[string]any{"execution_node": browsers.options.Node, "path": saved}, nil
}
