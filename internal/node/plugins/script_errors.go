type scriptException struct {
	Message  *string `json:"message"`
	Code     *string `json:"code"`
	Identity *string `json:"identity"`
	Category string  `json:"category"`
}

const scriptIntrinsics = `(() => {
  const descriptor = Object.getOwnPropertyDescriptor;
  const own = Object.hasOwn;
  const prototype = Object.getPrototypeOf;
  const apply = Reflect.apply;
  const parse = JSON.parse;
  const nativeError = Error.isError;
  const resolve = Promise.resolve.bind(Promise);
  const then = Function.prototype.call.bind(Promise.prototype.then);
  const kinds = [['Error','error'],['TypeError','type_error'],['RangeError','range_error'],
    ['ReferenceError','reference_error'],['SyntaxError','syntax_error'],['URIError','uri_error'],
    ['EvalError','eval_error'],['AggregateError','aggregate_error']]
    .filter(([name]) => typeof globalThis[name] === 'function')
    .map(([name, kind]) => [globalThis[name].prototype, kind]);
  const field = (error, key, limit) => {
    const property = descriptor(error, key);
    return property && own(property, 'value')
      && typeof property.value === 'string' && property.value.length <= limit
      ? property.value : null;
  };
  const inspect = error => {
    if (!nativeError(error)) return {message:null,code:null,identity:null,category:'thrown_value'};
    let category = 'unknown';
    let current = prototype(error);
    for (let depth=0; current && depth<8; depth++, current=prototype(current)) {
      for (let index=0; index<kinds.length; index++) {
        if (current === kinds[index][0]) {
          category = kinds[index][1];
          current = null;
          break;
        }
      }
      if (current === null) break;
    }
    return {message:field(error,'message',1024),code:field(error,'code',32),
      identity:field(error,'sailryFault',36),category};
  };
  return {
    inspect,
    watch(promise) {
      const state = {done:false, failed:false, value:undefined};
      then(promise,
        value => {state.done=true; state.value=value},
        error => {state.done=true; state.failed=true; state.value=error});
      return state;
    },
    invoke(exports, handler, input) {
      return then(then(resolve(), () => apply(exports[handler],undefined,[parse(input)])),
        value => ({success:true,value}),
        error => ({success:false,error:inspect(error)}));
    },
    has(exports, handler) {
      const value = exports[handler];
      return value === undefined ? false : typeof value === 'function' ? true : null;
    }
  };
})()`

func (runtime *scriptVM) exception(value moejs.Value) error {
	if err := runtime.arm(); err != nil {
		return err
	}
	if runtime.pure {
		return scriptInvalid("plugin translation failed")
	}
	fields, err := runtime.vm.CallFunction(runtime.inspect, moejs.Undefined(), value)
	if err != nil {
		return runtime.engine(err)
	}
	if err := runtime.arm(); err != nil {
		return err
	}
	encoded, err := runtime.vm.AppendJSON(nil, fields)
	if err != nil {
		return runtime.engine(err)
	}
	var exception scriptException
	if err := json.Unmarshal(encoded, &exception); err != nil {
		return scriptInvalid("plugin JavaScript execution failed")
	}
	return runtime.fault(exception)
}

func (runtime *scriptVM) fault(exception scriptException) error {
	if err := scriptCheck(runtime.ctx, runtime.deadline, runtime.pure); err != nil {
		return err
	}
	if runtime.pure {
		return scriptInvalid("plugin translation failed")
	}
	if exception.Identity != nil && runtime.bridge != nil {
		if fault := runtime.bridge.faults[*exception.Identity]; fault != nil {
			delete(runtime.bridge.faults, *exception.Identity)
			return fault
		}
	}
	code := protocol.ErrorCodeInvalidRequest
	if exception.Code != nil {
		encoded, _ := json.Marshal(*exception.Code)
		var selected protocol.ErrorCode
		if json.Unmarshal(encoded, &selected) == nil {
			code = selected
		}
	}
	message := "plugin JavaScript execution failed: Exception generated by QuickJS"
	if exception.Message != nil && *exception.Message != "" && len(*exception.Message) <= 1024 {
		detail := *exception.Message
		if exception.Category == "range_error" && detail == "Maximum call stack size exceeded" {
			detail = "stack overflow"
		}
		message = "plugin JavaScript execution failed: " + detail
	}
	fault := &protocol.Fault{Code: code, Message: message}
	encoded, _ := json.Marshal(exception.Category)
	category := protocol.NotificationSystemScriptExceptionUnknown
	_ = json.Unmarshal(encoded, &category)
	report := protocol.DefaultNotificationSystemSystemDiagnostic()
	report.Incident = protocol.NewRequestID()
	report.Source = protocol.NotificationSystemSystemSourcePluginCallback
	report.Phase = protocol.NotificationSystemDiagnosticPhaseCallback
	report.Reason = protocol.NotificationSystemDiagnosticReasonFailure
	report.Code = code
	report.Exception = &category
	report.Platform = goruntime.GOOS
	fault.Details = &protocol.FaultDetails{Kind: "system_diagnostic", Data: report}
	return fault
}

func scriptDiagnostic(err error, scope protocol.PluginContext, started, deadline time.Time) error {
	var fault *protocol.Fault
	if !errors.As(err, &fault) {
		fault = scriptInvalid("plugin JavaScript execution failed")
	}
	cloned := *fault
	report := protocol.DefaultNotificationSystemSystemDiagnostic()
	if cloned.Details != nil && cloned.Details.Kind == "system_diagnostic" {
		switch existing := cloned.Details.Data.(type) {
		case protocol.NotificationSystemSystemDiagnostic:
			report = existing
		case *protocol.NotificationSystemSystemDiagnostic:
			if existing != nil {
				report = *existing
			}
		}
	} else if cloned.Details != nil {
		return &cloned
	}
	if report.Incident == (protocol.RequestID{}) {
		report.Incident = protocol.NewRequestID()
	}
	report.Source = protocol.NotificationSystemSystemSourcePluginCallback
	report.Phase = protocol.NotificationSystemDiagnosticPhaseCallback
	report.Code = cloned.Code
	report.Reason = protocol.NotificationSystemDiagnosticReasonFailure
	if cloned.Code == protocol.ErrorCodeExpired {
		report.Reason = protocol.NotificationSystemDiagnosticReasonTimeout
	} else if cloned.Code == protocol.ErrorCodeCancelled {
		report.Reason = protocol.NotificationSystemDiagnosticReasonCancelled
	}
	report.Session, report.Turn, report.Worktree = scope.Session, scope.Turn, scope.Worktree
	budget := uint64(max(0, deadline.Sub(started).Milliseconds()))
	elapsed := uint64(max(0, time.Since(started).Milliseconds()))
	report.BudgetMs, report.ElapsedMs = &budget, &elapsed
	report.Platform = goruntime.GOOS
	cloned.Details = &protocol.FaultDetails{Kind: "system_diagnostic", Data: report}
	return &cloned
}
