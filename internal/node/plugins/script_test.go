func scriptTestBundle(source string) ScriptBundle {
	entry := "dev.sailry.platform/host/main.js"
	return ScriptBundle{Entry: entry, Files: map[string]string{entry: source}}
}

func scriptTestEnvironment() ScriptEnvironment {
	scope := protocol.DefaultPluginContext()
	scope.Package = protocol.PluginReference{Name: "fixture", Digest: strings.Repeat("a", 64), SettingsRevision: 9_007_199_254_740_993}
	return ScriptEnvironment{Context: scope, Target: protocol.NodeID{1}, Deadline: time.Now().Add(ScriptCallTimeout)}
}

func scriptTestRun(t *testing.T, source string, dispatch ScriptDispatch) (json.RawMessage, error) {
	t.Helper()
	return RunCallback(context.Background(), scriptTestBundle(source), "run", map[string]any{"value": 7}, scriptTestEnvironment(), false, dispatch)
}

func scriptTestFault(t *testing.T, err error, code protocol.ErrorCode) *protocol.Fault {
	t.Helper()
	var fault *protocol.Fault
	if !errors.As(err, &fault) || fault.Code != code {
		t.Fatalf("fault = %v; want %s", err, code)
	}
	return fault
}

func scriptTestJSON(t *testing.T, actual json.RawMessage, expected string) {
	t.Helper()
	left, leftError := scriptDecodeJSON(actual)
	right, rightError := scriptDecodeJSON([]byte(expected))
	if leftError != nil || rightError != nil || !reflect.DeepEqual(left, right) {
		t.Fatalf("JSON = %s; want %s", actual, expected)
	}
}

func TestScriptContracts(t *testing.T) {
	t.Parallel()
	t.Run("modules promises and fresh globals", func(t *testing.T) {
		bundle := scriptTestBundle(`import {add} from './math.js'; export async function run(input) {globalThis.count=(globalThis.count??0)+1;return {value:await Promise.resolve(add(input.value)),count:globalThis.count};}`)
		bundle.Files["dev.sailry.platform/host/math.js"] = "export const add=value=>value+1"
		for range 2 {
			value, err := RunCallback(context.Background(), bundle, "run", map[string]int{"value": 7}, scriptTestEnvironment(), false, nil)
			if err != nil {
				t.Fatal(err)
			}
			scriptTestJSON(t, value, `{"value":8,"count":1}`)
		}
	})
	t.Run("native errors without authored accessors", func(t *testing.T) {
		for _, source := range []string{
			"export function run(){throw new Error('Goal changed')}",
			"export async function run(){throw new Error('Goal changed')}",
			"throw new Error('Goal changed');export function run(){}",
			"export function run(){Object.getOwnPropertyDescriptor=()=>{while(true){}};throw new Error('Goal changed')}",
		} {
			_, err := scriptTestRun(t, source, nil)
			fault := scriptTestFault(t, err, protocol.ErrorCodeInvalidRequest)
			if fault.Message != "plugin JavaScript execution failed: Goal changed" {
				t.Fatal(fault.Message)
			}
		}
		for _, source := range []string{
			"export function run(){throw {get message(){while(true){}},toString(){while(true){}}}}",
			"export function run(){const error=new Error();Object.defineProperty(error,'message',{get(){while(true){}}});throw error}",
			"export function run(){throw new Proxy(new Error('hidden'),{getOwnPropertyDescriptor(){while(true){}}})}",
			"export function run(){throw new Error('🙂'.repeat(300))}",
		} {
			_, err := scriptTestRun(t, source, nil)
			fault := scriptTestFault(t, err, protocol.ErrorCodeInvalidRequest)
			if fault.Message != "plugin JavaScript execution failed: Exception generated by QuickJS" {
				t.Fatal(fault.Message)
			}
		}
	})
	t.Run("diagnostic classification", func(t *testing.T) {
		_, err := scriptTestRun(t, `export async function run(){const error=new RangeError('PRIVATE_PAYLOAD');Object.defineProperty(error,'name',{get(){while(true){}}});throw error}`, nil)
		fault := scriptTestFault(t, err, protocol.ErrorCodeInvalidRequest)
		if fault.Details == nil || fault.Details.Kind != "system_diagnostic" {
			t.Fatal("script diagnostic is missing")
		}
		report := fault.Details.Data.(protocol.NotificationSystemSystemDiagnostic)
		if report.Exception == nil || *report.Exception != protocol.NotificationSystemScriptExceptionRangeError {
			t.Fatalf("exception = %v", report.Exception)
		}
		encoded, _ := json.Marshal(report)
		if strings.Contains(string(encoded), "PRIVATE_PAYLOAD") {
			t.Fatal("diagnostic exposed an authored payload")
		}
	})
	t.Run("ambient resources and invalid results", func(t *testing.T) {
		value, err := scriptTestRun(t, "export function run(){return [typeof process,typeof fetch,typeof require,typeof document,typeof console]}", nil)
		if err != nil {
			t.Fatal(err)
		}
		scriptTestJSON(t, value, `["undefined","undefined","undefined","undefined","undefined"]`)
		for _, source := range []string{
			"import 'std';export function run(){}",
			"import '/etc/passwd';export function run(){}",
			"export function run(){const value={};value.self=value;return value}",
			"export function run(){return undefined}",
			fmt.Sprintf("export function run(){return 'x'.repeat(%d)}", ScriptMaxDataBytes),
		} {
			if _, err := scriptTestRun(t, source, nil); err == nil {
				t.Fatalf("script unexpectedly succeeded: %s", source)
			}
		}
	})
}

func TestScriptControls(t *testing.T) {
	t.Parallel()
	t.Run("recursive stack overflow preserves host", func(t *testing.T) {
		_, err := scriptTestRun(t, "export function run(){function recurse(){return recurse()}return recurse()}", nil)
		fault := scriptTestFault(t, err, protocol.ErrorCodeInvalidRequest)
		if fault.Message != "plugin JavaScript execution failed: stack overflow" {
			t.Fatalf("stack overflow = %s", fault.Message)
		}
		value, err := scriptTestRun(t, "export function run(){return 'host survived'}", nil)
		if err != nil {
			t.Fatal(err)
		}
		scriptTestJSON(t, value, `"host survived"`)
	})
	t.Run("memory is bounded", func(t *testing.T) {
		_, err := scriptTestRun(t, "export function run(){const values=[];while(true)values.push(new Array(100000).fill('memory'))}", nil)
		fault := scriptTestFault(t, err, protocol.ErrorCodeInvalidRequest)
		if fault.Message != "plugin JavaScript execution failed: out of memory" {
			t.Fatalf("memory limit = %s", fault.Message)
		}
		value, err := scriptTestRun(t, "export function run(){return 'host survived'}", nil)
		if err != nil {
			t.Fatal(err)
		}
		scriptTestJSON(t, value, `"host survived"`)
	})
	t.Run("deadlines and cancellation", func(t *testing.T) {
		for _, source := range []string{
			"export function run(){while(true){}}",
			"export async function run(){while(true)await Promise.resolve()}",
			"export function run(){return {get value(){while(true){}}}}",
		} {
			environment := scriptTestEnvironment()
			environment.Deadline = time.Now().Add(25 * time.Millisecond)
			_, err := RunCallback(context.Background(), scriptTestBundle(source), "run", nil, environment, false, nil)
			scriptTestFault(t, err, protocol.ErrorCodeExpired)
		}
		ctx, cancel := context.WithCancel(context.Background())
		cancel()
		_, err := RunCallback(ctx, scriptTestBundle("export function run(){return null}"), "run", nil, scriptTestEnvironment(), false, nil)
		scriptTestFault(t, err, protocol.ErrorCodeCancelled)
		_, err = scriptTestRun(t, "export function run(){return new Promise(()=>{})}", nil)
		scriptTestFault(t, err, protocol.ErrorCodeInvalidRequest)
	})
	t.Run("interrupted dispatch retains uncertain outcome", func(t *testing.T) {
		ctx, cancel := context.WithCancel(context.Background())
		defer cancel()
		calls := 0
		_, err := RunCallback(ctx, scriptTestBundle(`import {setValue,completeRequest} from 'sailry/sdk';export async function run(){await completeRequest(setValue('once',true,'0'));return 'not a receipt'}`), "run", nil, scriptTestEnvironment(), false, func(context.Context, protocol.Request) (protocol.Output, error) {
			calls++
			cancel()
			return protocol.Output{}, &protocol.Fault{Code: protocol.ErrorCodeOutcomeUnknown, Message: "original SDK outcome"}
		})
		fault := scriptTestFault(t, err, protocol.ErrorCodeOutcomeUnknown)
		if fault.Message != "original SDK outcome" || calls != 1 {
			t.Fatalf("outcome = %v; calls = %d", fault, calls)
		}
	})
}

func TestScriptSDK(t *testing.T) {
	t.Parallel()
	t.Run("captured scope exact revisions and repeated drafts", func(t *testing.T) {
		environment := scriptTestEnvironment()
		var calls []protocol.Request
		dispatch := func(_ context.Context, request protocol.Request) (protocol.Output, error) {
			calls = append(calls, request)
			return protocol.Output{Kind: "plugin_value", Data: protocol.PluginStorageEntry{Key: "counter", Revision: 9_007_199_254_740_993, Present: true, Value: json.RawMessage("1")}}, nil
		}
		value, err := RunCallback(context.Background(), scriptTestBundle(`
import {context,getValue,setValue,completeRequest,forgetRequest} from 'sailry/sdk';
export async function run(){const old=await getValue('counter');const id=setValue('counter',2,old.revision);const first=await completeRequest(id);const second=await completeRequest(id);forgetRequest(id);return {revision:old.revision,settings:context().package.settings_revision,same:JSON.stringify(first)===JSON.stringify(second)}}`), "run", nil, environment, false, dispatch)
		if err != nil {
			t.Fatal(err)
		}
		scriptTestJSON(t, value, `{"revision":"9007199254740993","settings":"9007199254740993","same":true}`)
		if len(calls) != 3 || !reflect.DeepEqual(calls[1], calls[2]) {
			t.Fatalf("draft request identities were not retained: %v", calls)
		}
		for _, request := range calls {
			if request.Plugin == nil || !reflect.DeepEqual(*request.Plugin, environment.Context) {
				t.Fatal("callback changed its captured scope")
			}
		}
		payload := calls[1].Command.Data.(*protocol.CommandWritePluginValuePayload)
		if payload.ExpectedRevision != 9_007_199_254_740_993 {
			t.Fatal("revision precision was lost")
		}
	})
	t.Run("host faults retain details", func(t *testing.T) {
		expected := &protocol.Fault{Code: protocol.ErrorCodeRevisionConflict, Message: "plugin value changed", Details: &protocol.FaultDetails{Kind: "plugin_value_conflict"}}
		_, err := scriptTestRun(t, `import {getValue} from 'sailry/sdk';export async function run(){return await getValue('counter')}`, func(context.Context, protocol.Request) (protocol.Output, error) {
			return protocol.Output{}, expected
		})
		if !reflect.DeepEqual(err, expected) {
			t.Fatalf("host fault = %#v; want %#v", err, expected)
		}
		value, err := scriptTestRun(t, `import {getValue} from 'sailry/sdk';export async function run(){try{await getValue('counter')}catch{return 'handled'}}`, func(context.Context, protocol.Request) (protocol.Output, error) {
			return protocol.Output{}, expected
		})
		if err != nil {
			t.Fatal(err)
		}
		scriptTestJSON(t, value, `"handled"`)
	})
	t.Run("tool write identity staging and plan fence", func(t *testing.T) {
		call := protocol.NewRequestID()
		source := `import {setValue,completeRequest,callId,stageTurnState,readTurnState} from 'sailry/sdk';export async function run(){stageTurnState({count:readTurnState().count+1});const id=setValue('counter',1,'0');await completeRequest(id);return {id,call:callId()}}`
		var identities []protocol.RequestID
		for range 2 {
			execution := &ScriptExecution{CallID: &call, Mode: protocol.WorkModeCode, Turn: json.RawMessage(`{"count":1}`)}
			_, err := RunTool(context.Background(), scriptTestBundle(source), "run", nil, scriptTestEnvironment(), func(_ context.Context, request protocol.Request) (protocol.Output, error) {
				identities = append(identities, request.ID)
				return protocol.Output{Kind: "plugin_value", Data: protocol.PluginStorageEntry{Key: "counter", Revision: 1, Present: true, Value: json.RawMessage("1")}}, nil
			}, execution)
			if err != nil {
				t.Fatal(err)
			}
			scriptTestJSON(t, execution.StagedTurn, `{"count":2}`)
		}
		if len(identities) != 2 || identities[0] != identities[1] || identities[0] == call {
			t.Fatal("tool writes did not retain derived identity")
		}
		for _, execution := range []*ScriptExecution{{CallID: &call, Mode: protocol.WorkModePlan}, {CallID: &call, Mode: protocol.WorkModeCode, ReadOnly: true}} {
			_, err := RunTool(context.Background(), scriptTestBundle(`import {setValue} from 'sailry/sdk';export function run(){return setValue('counter',1,'0')}`), "run", nil, scriptTestEnvironment(), nil, execution)
			scriptTestFault(t, err, protocol.ErrorCodePermissionDenied)
		}
	})
	t.Run("read callbacks deny nondurable mutations", func(t *testing.T) {
		source := `import {prepareRequest,completeRequest} from 'sailry/sdk';export async function run(){return await completeRequest(prepareRequest({kind:'cancel_web_fetch',data:{request:'00000000-0000-4000-8000-000000000001'}}))}`
		value, err := RunCallback(context.Background(), scriptTestBundle(source), "run", nil, scriptTestEnvironment(), true, func(context.Context, protocol.Request) (protocol.Output, error) {
			t.Fatal("mutation reached the service")
			return protocol.Output{}, nil
		})
		if err != nil {
			t.Fatal(err)
		}
		var outcome map[string]protocol.Fault
		if json.Unmarshal(value, &outcome) != nil || outcome["Err"].Code != protocol.ErrorCodePermissionDenied {
			t.Fatalf("read-only outcome = %s", value)
		}
	})
	t.Run("revision adapters preserve dispatch list shapes", func(t *testing.T) {
		command, _ := scriptDecodeJSON([]byte(`{"kind":"dispatch","data":{"action":{"kind":"save_handler","data":{"callback":{"command":{"kind":"start_session","data":{"team":{"revision":"9007199254740993"}}}}}}}}`))
		if err := scriptCommandRevisions(command); err != nil {
			t.Fatal(err)
		}
		if scriptAt(command, "data", "action", "data", "callback", "command", "data", "team", "revision") != json.Number("9007199254740993") {
			t.Fatal("nested team revision was not converted")
		}
		for _, revision := range []any{json.Number("9007199254740993"), "01", json.Number("-1"), json.Number("1.5")} {
			if _, err := scriptRevision(revision, false, "invalid revision"); err == nil {
				t.Fatalf("accepted inexact revision %v", revision)
			}
		}
		for _, kind := range []string{"handler", "handlers"} {
			record, _ := scriptDecodeJSON([]byte(`{"revision":0,"callback":{"command":{"data":{"team":{"revision":9007199254740993}}}}}`))
			var data any = record
			if kind == "handlers" {
				data = []any{record}
			}
			output := map[string]any{"kind": kind, "data": data}
			scriptDispatchOutputRevisions(output)
			expected := any("0")
			if kind == "handlers" {
				expected = json.Number("0")
			}
			if scriptAt(record, "revision") != expected || scriptAt(record, "callback", "command", "data", "team", "revision") != "9007199254740993" {
				t.Fatalf("dispatch shape changed: %v", output)
			}
		}
	})
}

func TestScriptTranslations(t *testing.T) {
	t.Parallel()
	t.Run("retained pure state", func(t *testing.T) {
		session, err := NewTranslation(context.Background(), scriptTestBundle(`import {parseJson,version} from 'sailry/adapter';let count=0;export async function decode(input){return {version,count:++count,input:parseJson(input),io:[typeof fetch,typeof process,typeof console,typeof __sailry,typeof require]}}`))
		if err != nil {
			t.Fatal(err)
		}
		defer session.Close()
		if present, err := session.HasExport("decode"); err != nil || !present {
			t.Fatalf("decode presence = %v %v", present, err)
		}
		if present, err := session.HasExport("missing"); err != nil || present {
			t.Fatalf("missing presence = %v %v", present, err)
		}
		for index := 1; index <= 2; index++ {
			value, err := session.Call("decode", `{"text":"fixture"}`, 4096)
			if err != nil {
				t.Fatal(err)
			}
			scriptTestJSON(t, value, fmt.Sprintf(`{"version":"v1","count":%d,"input":{"text":"fixture"},"io":["undefined","undefined","undefined","undefined","undefined"]}`, index))
		}
	})
	t.Run("pure imports and failed session", func(t *testing.T) {
		for _, module := range []string{"sailry/sdk", "sailry/models", "node:fs", "https://example.test/code.js"} {
			if session, err := NewTranslation(context.Background(), scriptTestBundle(fmt.Sprintf("import '%s';export function decode(){return null}", module))); err == nil {
				session.Close()
				t.Fatalf("pure session accepted %s", module)
			}
		}
		session, err := NewTranslation(context.Background(), scriptTestBundle("export function decode(input){throw new Error(input.token)}"))
		if err != nil {
			t.Fatal(err)
		}
		defer session.Close()
		_, err = session.Call("decode", map[string]string{"token": "private-authentication-exchange"}, 4096)
		fault := scriptTestFault(t, err, protocol.ErrorCodeInvalidRequest)
		if fault.Message != "plugin translation failed" {
			t.Fatal(fault)
		}
		if _, err := session.Call("decode", nil, 4096); err == nil {
			t.Fatal("failed translation session was reused")
		}
	})
	t.Run("byte budgets and cancellation", func(t *testing.T) {
		ctx, cancel := context.WithCancel(context.Background())
		defer cancel()
		session, err := NewTranslation(ctx, scriptTestBundle("export function decode(input){return input}"))
		if err != nil {
			t.Fatal(err)
		}
		defer session.Close()
		if _, err := session.Call("decode", strings.Repeat("x", 8192), 4096); err == nil {
			t.Fatal("oversized translation input was accepted")
		}
		cancel()
		_, err = session.Call("decode", nil, 4096)
		scriptTestFault(t, err, protocol.ErrorCodeCancelled)
	})
}

func TestBundledScriptEntrypoints(t *testing.T) {
	t.Parallel()
	directories, err := fs.ReadDir(bundled.Plugins, "plugins")
	if err != nil {
		t.Fatal(err)
	}
	for _, directory := range directories {
		if !directory.IsDir() {
			continue
		}
		root := "plugins/" + directory.Name() + "/"
		manifest, err := fs.ReadFile(bundled.Plugins, root+"plugin.json")
		if errors.Is(err, fs.ErrNotExist) {
			continue
		}
		if err != nil {
			t.Fatal(err)
		}
		value, err := scriptDecodeJSON(manifest)
		if err != nil {
			t.Fatal(err)
		}
		extension := scriptAt(value, "extensions", "dev.sailry.platform")
		check := func(declaration any, pure bool) {
			entry, ok := scriptAt(declaration, "entry").(string)
			if !ok {
				return
			}
			t.Run(directory.Name()+"/"+entry, func(t *testing.T) {
				bundle := ScriptBundle{Entry: entry, Files: map[string]string{}}
				names := []string{entry}
				resources, _ := scriptAt(declaration, "resources").([]any)
				for _, resource := range resources {
					name, _ := resource.(string)
					if strings.HasSuffix(name, ".js") || strings.HasSuffix(name, ".mjs") {
						names = append(names, name)
					}
				}
				for _, name := range names {
					source, err := fs.ReadFile(bundled.Plugins, root+name)
					if err != nil {
						t.Fatal(err)
					}
					bundle.Files[name] = string(source)
				}
				if pure {
					session, err := NewTranslation(context.Background(), bundle)
					if err != nil {
						t.Fatal(err)
					}
					session.Close()
					return
				}
				environment := scriptTestEnvironment()
				environment.Context.Package.Name = directory.Name()
				bridge := &scriptBridge{
					ctx: context.Background(), deadline: environment.Deadline, target: environment.Target, scope: environment.Context,
					drafts: map[string]scriptDraft{}, faults: map[string]*protocol.Fault{}, installations: map[protocol.RequestID]bool{},
				}
				runtime, err := newScriptVM(context.Background(), bundle, environment.Deadline, bridge, false)
				if err != nil {
					t.Fatal(err)
				}
				runtime.close()
			})
		}
		check(scriptAt(extension, "host"), false)
		var scripts func(any)
		scripts = func(value any) {
			switch value := value.(type) {
			case map[string]any:
				if _, exists := value["entry"]; exists {
					check(value, true)
					return
				}
				for _, nested := range value {
					scripts(nested)
				}
			case []any:
				for _, nested := range value {
					scripts(nested)
				}
			}
		}
		for _, field := range []string{"model_auth", "model_adapters", "connectors"} {
			scripts(scriptAt(extension, field))
		}
	}
}
