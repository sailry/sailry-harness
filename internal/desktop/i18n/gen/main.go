// Gen copies the keys listed in keys.txt from the repository's locale files
// into this package's catalogs. It only reads the source directory.
package main

import (
	"bufio"
	"flag"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"go.yaml.in/yaml/v3"
)

func main() {
	src := flag.String("src", "", "source locales directory")
	keysFile := flag.String("keys", "keys.txt", "keys to copy, one per line")
	out := flag.String("out", "locales", "output directory")
	flag.Parse()
	keys := readKeys(*keysFile)
	english, err := readLang(*src, "en")
	if err != nil {
		log.Fatal(err)
	}
	missing := false
	for _, lang := range []string{"en", "zh-CN", "zh-TW", "ja", "ko", "fr", "de", "es", "pt-BR", "ru"} {
		all, err := readLang(*src, lang)
		if err != nil {
			log.Fatal(err)
		}
		var b strings.Builder
		fmt.Fprintf(&b, "# Generated by internal/desktop/i18n/gen from locales; do not edit.\n")
		for _, k := range keys {
			v, ok := all[k]
			if !ok && lang != "en" && lang != "zh-CN" {
				v, ok = english[k]
			}
			if !ok {
				log.Printf("%s: missing %s", lang, k)
				missing = true
				continue
			}
			q, _ := yaml.Marshal(map[string]string{k: v})
			b.Write(q)
		}
		if err := os.WriteFile(filepath.Join(*out, lang+".yml"), []byte(b.String()), 0o644); err != nil {
			log.Fatal(err)
		}
	}
	if missing {
		os.Exit(1)
	}
}

func readKeys(path string) []string {
	f, err := os.Open(path)
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()
	var keys []string
	s := bufio.NewScanner(f)
	for s.Scan() {
		if k := strings.TrimSpace(s.Text()); k != "" && !strings.HasPrefix(k, "#") {
			keys = append(keys, k)
		}
	}
	return keys
}

// readLang merges every catalog of a language: <lang>.yml and *.<lang>.yml.
// A key belongs to one file: one defined in two files of the language is an
// error naming both, whether or not the values agree, so no file silently
// overrides another. The decoder already refuses a key repeated in one file.
func readLang(dir, lang string) (map[string]string, error) {
	paths, _ := filepath.Glob(filepath.Join(dir, "*."+lang+".yml"))
	paths = append(paths, filepath.Join(dir, lang+".yml"))
	sort.Strings(paths)
	all, from := map[string]string{}, map[string]string{}
	var duplicates []string
	for _, p := range paths {
		data, err := os.ReadFile(p)
		if err != nil {
			continue
		}
		m := map[string]string{}
		if err := yaml.Unmarshal(data, &m); err != nil {
			return nil, fmt.Errorf("%s: %w", p, err)
		}
		for k, v := range m {
			if first, defined := from[k]; defined {
				duplicates = append(duplicates, fmt.Sprintf("%s: %s and %s", k, filepath.Base(first), filepath.Base(p)))
				continue
			}
			all[k], from[k] = v, p
		}
	}
	if len(duplicates) > 0 {
		sort.Strings(duplicates)
		return nil, fmt.Errorf("%s: %d keys are defined twice:\n  %s", lang, len(duplicates), strings.Join(duplicates, "\n  "))
	}
	return all, nil
}
