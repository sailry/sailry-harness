// Gen copies the keys listed in keys.txt from the repository's locale files
// into this package's catalogs. It only reads the source directory.
package main

import (
	"bufio"
	"flag"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"go.yaml.in/yaml/v3"
)

func main() {
	src := flag.String("src", "", "source locales directory")
	keysFile := flag.String("keys", "keys.txt", "keys to copy, one per line")
	out := flag.String("out", "locales", "output directory")
	flag.Parse()
	keys := readKeys(*keysFile)
	missing := false
	for _, lang := range []string{"en", "zh-CN"} {
		all := readLang(*src, lang)
		var b strings.Builder
		fmt.Fprintf(&b, "# Generated by internal/desktop/i18n/gen from locales; do not edit.\n")
		for _, k := range keys {
			v, ok := all[k]
			if !ok {
				log.Printf("%s: missing %s", lang, k)
				missing = true
				continue
			}
			q, _ := yaml.Marshal(map[string]string{k: v})
			b.Write(q)
		}
		if err := os.WriteFile(filepath.Join(*out, lang+".yml"), []byte(b.String()), 0o644); err != nil {
			log.Fatal(err)
		}
	}
	if missing {
		os.Exit(1)
	}
}

func readKeys(path string) []string {
	f, err := os.Open(path)
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()
	var keys []string
	s := bufio.NewScanner(f)
	for s.Scan() {
		if k := strings.TrimSpace(s.Text()); k != "" && !strings.HasPrefix(k, "#") {
			keys = append(keys, k)
		}
	}
	return keys
}

// readLang merges every catalog of a language: <lang>.yml and *.<lang>.yml.
func readLang(dir, lang string) map[string]string {
	paths, _ := filepath.Glob(filepath.Join(dir, "*."+lang+".yml"))
	paths = append(paths, filepath.Join(dir, lang+".yml"))
	sort.Strings(paths)
	all := map[string]string{}
	for _, p := range paths {
		data, err := os.ReadFile(p)
		if err != nil {
			continue
		}
		m := map[string]string{}
		if err := yaml.Unmarshal(data, &m); err != nil {
			log.Fatalf("%s: %v", p, err)
		}
		for k, v := range m {
			all[k] = v
		}
	}
	return all
}
